-- Tags
CREATE TABLE tb_tag (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    name         varchar(60) NOT NULL,
    creator_uuid uuid NOT NULL,
    CONSTRAINT tb_tag_pkey PRIMARY KEY (id),
    CONSTRAINT fk_tag_creator FOREIGN KEY (creator_uuid) REFERENCES tb_user (uuid),
    CONSTRAINT uk_tag_creator_name UNIQUE (creator_uuid, name)
);
CREATE INDEX idx_tag_creator ON tb_tag (creator_uuid);

-- Theme <-> Tag M2M
CREATE TABLE tb_theme_tag (
    theme_id bigint NOT NULL,
    tag_id   bigint NOT NULL,
    CONSTRAINT tb_theme_tag_pkey PRIMARY KEY (theme_id, tag_id),
    CONSTRAINT fk_theme_tag_theme FOREIGN KEY (theme_id) REFERENCES tb_theme (id) ON DELETE CASCADE,
    CONSTRAINT fk_theme_tag_tag   FOREIGN KEY (tag_id)   REFERENCES tb_tag   (id) ON DELETE CASCADE
);
CREATE INDEX idx_theme_tag_tag ON tb_theme_tag (tag_id);

-- Theme like (unique user+theme)
CREATE TABLE tb_theme_like (
    id        bigint GENERATED BY DEFAULT AS IDENTITY,
    user_uuid uuid   NOT NULL,
    theme_id  bigint NOT NULL,
    created_at timestamp NOT NULL DEFAULT now(),
    CONSTRAINT tb_theme_like_pkey PRIMARY KEY (id),
    CONSTRAINT fk_theme_like_user  FOREIGN KEY (user_uuid) REFERENCES tb_user  (uuid) ON DELETE CASCADE,
    CONSTRAINT fk_theme_like_theme FOREIGN KEY (theme_id)  REFERENCES tb_theme (id)   ON DELETE CASCADE,
    CONSTRAINT uk_theme_like_user_theme UNIQUE (user_uuid, theme_id)
);
CREATE INDEX idx_theme_like_theme ON tb_theme_like (theme_id);

-- Question explanation
ALTER TABLE tb_question
    ADD COLUMN IF NOT EXISTS explanation text;

-- Theme feedback
CREATE TABLE tb_theme_feedback (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    theme_id   bigint NOT NULL,
    user_uuid  uuid   NOT NULL,
    text       text   NOT NULL,
    created_at timestamp NOT NULL DEFAULT now(),
    CONSTRAINT tb_theme_feedback_pkey PRIMARY KEY (id),
    CONSTRAINT fk_theme_feedback_theme FOREIGN KEY (theme_id)  REFERENCES tb_theme (id)   ON DELETE CASCADE,
    CONSTRAINT fk_theme_feedback_user  FOREIGN KEY (user_uuid) REFERENCES tb_user  (uuid) ON DELETE CASCADE
);
CREATE INDEX idx_theme_feedback_theme ON tb_theme_feedback (theme_id);
CREATE INDEX idx_theme_feedback_user  ON tb_theme_feedback (user_uuid);

-- Optional student uuid to link statistic with logged-in player
ALTER TABLE tb_statistic
    ADD COLUMN IF NOT EXISTS student_uuid uuid;
CREATE INDEX IF NOT EXISTS idx_statistic_student ON tb_statistic (student_uuid);

-- Statistic feedback (creator -> statistic)
CREATE TABLE tb_statistic_feedback (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    statistic_id  bigint NOT NULL,
    creator_uuid  uuid   NOT NULL,
    text          text   NOT NULL,
    created_at    timestamp NOT NULL DEFAULT now(),
    CONSTRAINT tb_statistic_feedback_pkey PRIMARY KEY (id),
    CONSTRAINT fk_stat_feedback_statistic FOREIGN KEY (statistic_id) REFERENCES tb_statistic (id) ON DELETE CASCADE,
    CONSTRAINT fk_stat_feedback_creator   FOREIGN KEY (creator_uuid) REFERENCES tb_user      (uuid) ON DELETE CASCADE
);
CREATE INDEX idx_stat_feedback_statistic ON tb_statistic_feedback (statistic_id);
CREATE INDEX idx_stat_feedback_creator   ON tb_statistic_feedback (creator_uuid);
